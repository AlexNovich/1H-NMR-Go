"""Run frozen Windows checks and create a sanitized package inventory/identity."""
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from pathlib import Path

from bruker_nmr.demo_input import write_demo_input

ROOT = Path(__file__).resolve().parents[1]


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    package = ROOT / "dist/NMR-go"
    executable = package / "NMR-go.exe"
    output = ROOT / "dist/Smoke with spaces/Проверка"
    output.mkdir(parents=True, exist_ok=True)
    identity = json.loads((ROOT / "build/package-inputs/build_identity.json").read_text(encoding="utf-8-sig"))
    reports = []
    for i in range(3):
        result = output / f"self-test-{i}.json"
        result.unlink(missing_ok=True)
        started = time.perf_counter()
        env = dict(os.environ, QT_SCALE_FACTOR=('1', '1.5', '2')[i])
        subprocess.run([str(executable), "--self-test", str(result)],
                       cwd=output, env=env, check=True, timeout=120)
        elapsed = time.perf_counter() - started
        report = json.loads(result.read_text(encoding="utf-8"))
        if report["status"] != "passed" or len(report["checks"]) != 17:
            raise RuntimeError("Incomplete frozen self-test")
        if report['requested_qt_scale_factor'] != env['QT_SCALE_FACTOR'] or not report['network_connect_blocked']:
            raise RuntimeError('Frozen DPI/offline self-test evidence incomplete')
        reports.append({"run": i, "qt_scale_factor": env["QT_SCALE_FACTOR"], "process_seconds": elapsed, **report})
    benchmark_path = output / 'phase-benchmark.json'
    started = time.perf_counter()
    subprocess.run([str(executable), '--phase-benchmark', str(benchmark_path)],
                   cwd=output, check=True, timeout=600)
    phase_benchmark = json.loads(benchmark_path.read_text(encoding='utf-8'))
    phase_benchmark['cold_process_total_seconds'] = time.perf_counter()-started
    shutil.copy2(output / "self-test-0.pdf", package / "NMR-go-demo.pdf")
    write_demo_input(package / "synthetic-example.zip")
    for part in ('main', 'phase', 'baseline', 'pdf-preview'):
        shutil.copy2(output / f'self-test-0-{part}.png', package / f'REVIEW-synthetic-{part}.png')
    for name,path in reports[0]['pdf_examples'].items():
        shutil.copy2(output/path,package/f'REVIEW-synthetic-{name}.pdf')
    (package / "START-HERE.txt").write_text(
        f"NMR-go {identity['version']} — processed spectrum workbench\n\n"
        "Extract the entire folder. Start NMR-go.exe. Do not move the executable alone.\n"
        "No Python installation or internet connection is required at runtime.\n"
        "Starts with an artificial demo. Open ZIP/Open Folder loads verified 1D 1H pdata.\n"
        "Use Open ZIP with synthetic-example.zip for an entirely artificial input test.\n"
        "It is generated by NMR-go demo_input from independent Lorentzian parameters.\n"
        "No experimental measurements are included.\n"
        "Wheel over horizontal axis scales x; elsewhere on the plot scales y. Ctrl+drag pans.\n"
        "Rectangle Zoom, Pan and Full View have separate Previous view history (Backspace/Alt-left).\n"
        "Undo/Redo restores named edits, independently of navigation; Reset (Edit menu) restores opening state.\n"
        "The toolbar includes Save, Undo, Redo and Reference; View opens Integrals/Peaks/Appearance.\n"
        "Phase/Baseline use embedded context panels; navigation remains available.\n"
        "Phase pivot has ppm entry/drag; jog has Shift/Alt modifiers; Space compares original display only.\n"
        "Baseline Draw quiet range stays active for consecutive anchors. Escape exits drawing first.\n"
        "Preview is debounced and Apply stays explicit. Escape cancels once drawing has stopped.\n"
        "Integral values/brackets occupy a separate strip; right-click opens integral commands.\n"
        "Pick Peaks: click near an extremum or drag a rectangle to add maxima. Undo removes the batch.\n"
        "Peaks table controls Auto/All/Hidden labels and individual visibility without deletion.\n"
        "Reference sets a selected peak to zero without changing source arrays or areas.\n"
        "Appearance applies line width/colour/visibility immediately. Undo reverses these in-memory edits.\n"
        "View → Show grid toggles a dashed grid and carries it into PDF preview and export.\n"
        "Integrate mode creates ranges. Integral table edits bounds and assigns proton counts.\n"
        "Deleting a reference freezes the scale. Clear all starts fresh. Undo/Redo restores edits.\n"
        "File → Save annotations (Ctrl+S) writes integration and peaks to the selected processed pdata. ZIP Save opens a full extracted copy.\n"
        "Process from FID offers valid dataset-aware SI sizes and LB options and creates a separate unphased raw mode.\n"
        "Raw-only inputs also work. Undo restores operator data/annotations; Cancel retains them.\n"
        "Raw arbitrary units do not reuse operator integral scale; baseline remains Off.\n"
        "Phase opens relative PH0/PH1/pivot preview. Auto Phase proposes; Apply is explicit.\n"
        "Cancel retains arrays/history. Undo restores arrays, integrals and scale.\n"
        "LOW CONFIDENCE is recoverable with manual controls; inspect all signals.\n"
        "Imported normalization becomes unverified; an assigned reference is recomputed.\n"
        "Baseline starts Off. Choose explicit quiet ppm anchors, Constant or Linear, then Preview.\n"
        "Apply is undoable; Cancel is exact; Disable restores pre-baseline data.\n"
        "Preview shows a dashed baseline and before/after areas; no edge is assumed quiet.\n"
        "Phase after baseline uses pre-baseline data and requires refitting afterwards.\n"
        "Reprocessing raw data remaps ranges, recomputes areas and marks picks for review.\n"
        "REVIEW-synthetic-*.png are generated from artificial inputs for optional UX review.\n"
        "Export PDF (Ctrl+E) previews the captured current view, then Save PDF writes one landscape A4 page.\n"
        "Header is prefilled from available local metadata; edit or erase it before saving.\n"
        "Print uses a minimal ppm axis, vertical full integral values and upper clipping cues.\n"
        "Integral labels share one baseline with orthogonal leaders; zoom if one row cannot fit.\n"
        "Colour/width and full clipped integral values are preserved; no separate print profile.\n"
        "A PDF is not an editable project. Export before Discard returns to the spectrum.\n"
        "NMR-go-demo.pdf and REVIEW-synthetic-full/expanded.pdf are artificial checks only.\n"
        "Spectrum details exposes all verified acqus/procs parameters and current processing separately.\n"
        "Close exits; tray Open/Quit uses the same window/unsaved-edit checks. This is a release candidate.\n", encoding="utf-8")
    # Sources were explicit in the spec; also fail on known data/config names in outputs.
    forbidden = {"acqus", "procs", "fid", "ser", "1r", "1i", "2rr", "title", "intrng",
                 "peaklist.xml", "integrals.txt", "nmr-go-markup.json", ".nmr-go-save.lock", "people.json", "config.yaml", "bot.db", "state.db"}
    inventory = []
    for path in sorted(package.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(package).as_posix()
        if (path.name.lower() in forbidden or path.name.startswith((".env", ".nmr-go-backup-", ".nmr-go-write-"))
                or any(part.lower() in {"local_data", "reports", ".git", ".aws"}
                       for part in path.relative_to(package).parts)):
            raise RuntimeError(f"Forbidden package path: {rel}")
        inventory.append({"path": rel, "bytes": path.stat().st_size, "sha256": sha256(path)})
    manifest = {
        **identity, "python": platform.python_version(), "architecture": platform.machine(),
        "runner_image": os.environ.get("ImageOS", "local-windows"),
        "runner_image_version": os.environ.get("ImageVersion", "unavailable"),
        "lock_sha256": sha256(ROOT / "requirements/win-amd64.lock"),
        "packages": reports[0]["packages"], "frozen_runs": reports,
        "phase_benchmark": phase_benchmark,
        "editor_benchmark": json.loads((ROOT / 'build/package-inputs/editor-benchmark.json').read_text(encoding='utf-8')),
        "synthetic_input_origin": "synthetic-example.zip: generated by bruker_nmr.demo_input "
                                  "from independent Lorentzian parameters; no confidential inputs",
        "synthetic_review_origin": "REVIEW-synthetic-main/phase/baseline/pdf-preview.png and full/expanded.pdf generated by the "
                                   "frozen self-test on independent artificial fixtures only; "
                                   "no user measurements/reference screenshots",
        "measurement_note": "First after build, then two repeated starts; caches not forcibly cleared. "
                            "Process time includes dependency checks and PDF export. "
                            "Window-ready time is diagnostic-mode time to a Qt event callback.",
        "unpacked_bytes_before_manifest": sum(row["bytes"] for row in inventory),
        "file_count_before_manifest": len(inventory), "files": inventory,
        "acceptance": "Awaiting actual ordinary-user Windows 11 offline launch",
    }
    (package / "build-manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(json.dumps({"source_commit": identity["source_commit"],
                      "file_count": len(inventory),
                      "unpacked_bytes_before_manifest": manifest["unpacked_bytes_before_manifest"],
                      "window_ready_seconds": [r["window_ready_seconds"] for r in reports],
                      "phase_timing": phase_benchmark["timing"], "frozen_status": "passed"}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
